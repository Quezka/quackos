#!/usr/bin/env python3
"""Regenerates the Wayland protocol bindings of the shell (shell/quackshell/infra/protocols/) from shell/protocols/*.xml
with the scanner of pywayland (Debian's python3-pywayland 0.4.18, the same one the image ships). Run it by hand after
changing an XML file, and commit the result: the build does not need the scanner."""
import logging
import os
import pathlib
import shutil
import sys

from pywayland.scanner.protocol import Protocol

ROOT = pathlib.Path(__file__).resolve().parent.parent
XML = sorted((ROOT / "shell" / "protocols").glob("*.xml"))
OUT = ROOT / "shell" / "quackshell" / "infra" / "protocols"

logging.basicConfig(level=logging.INFO)
# the core protocol (wl_seat, wl_output...) is only read to resolve imports: pywayland ships its own bindings of it
CORE = os.environ.get("WAYLAND_XML", "/usr/share/wayland/wayland.xml")  # Debian: libwayland-dev
protocols = [Protocol.parse_file(str(p)) for p in XML]
imports = {i.name: p.name for p in [Protocol.parse_file(CORE)] + protocols for i in p.interface}
shutil.rmtree(OUT, ignore_errors=True)
OUT.mkdir(parents=True)
for p in protocols:
    p.output(str(OUT), imports)
(OUT / "__init__.py").write_text('"""Generated by scripts/gen-protocols.py: do not edit."""\n')
# the scanner imports the core interfaces from a sibling package; pywayland already ships them
for path in OUT.rglob("*.py"):
    text = path.read_text()
    path.write_text(text.replace("from ..wayland import", "from pywayland.protocol.wayland import"))
print("generated:", [p.name for p in protocols], "in", OUT, file=sys.stderr)
